/* ---------- Calcolo del carico ---------- */

const turniDi = data => db.turni[data] ?? db.config.turniDefault;
const capacita = data => turniDi(data) * MINUTI_TURNO;
const minutiCapi = capi => CAPI.reduce((s,c) => s + (Number(capi[c.k]) || 0) * db.config[c.tempo], 0);

/* Capi arrivati per giorno, di tutte le sedi: la stireria è una sola. */
/* Solo gli ordini ancora in lavorazione: quelli pronti non occupano più la stireria. */
const capiPerGiorno = () => db.carico;

const minutiArrivati = (giorni,data) => giorni[data] ? minutiCapi(giorni[data]) : 0;

/* Minuti in coda all'inizio di un giorno (prima della sua capacità), arretrato compreso. */
function codaAllInizio(giorni, data){
    const precedenti = Object.keys(giorni).filter(d => d < data).sort();
    if(!precedenti.length) return 0;
    let coda = 0;
    for(let d = daISO(precedenti[0]); dataISO(d) < data; d = sposta(d,1)){
        if(!lavorativo(d)) continue;
        const iso = dataISO(d);
        coda = Math.max(0, coda - capacita(iso)) + minutiArrivati(giorni,iso);
    }
    return coda;
}

function giornoFine(inizio, minuti){
    let d = daISO(inizio);
    for(let i = 0; i < 730; i++, d = sposta(d,1)){
        if(!lavorativo(d)) continue;
        minuti -= capacita(dataISO(d));
        if(minuti <= 0) return d;
    }
    return null;
}

/* Primo giorno di ritiro possibile per capi consegnati nel giorno "deposito". */
function primoRitiro(capi, deposito){
    const minuti = minutiCapi(capi);
    if(minuti <= 0) return null;
    const giorni = capiPerGiorno();
    const prima =
        Math.max(0, codaAllInizio(giorni,deposito) - capacita(deposito)) +
        minutiArrivati(giorni,deposito);
    const inizio = aggiungiLavorativi(daISO(deposito),1);
    const fine = giornoFine(dataISO(inizio), prima + minuti);
    return fine ? aggiungiLavorativi(fine,2) : null;
}

/*
Programma di lavoro: quali ordini si stirano in quale giorno.
Ordine di arrivo; ogni giorno si lavora ciò che è arrivato prima.
Restituisce { "YYYY-MM-DD": [{ ordine, minuti, inizia, finisce }] }.
*/
function programmaLavoro(){
    const ordini = db.ordini
        .filter(o => o.stato === "lavorazione")
        .sort((a,b) => a.data.localeCompare(b.data) || a.id - b.id);
    const programma = {};
    if(!ordini.length) return programma;

    const coda = [];
    let i = 0;
    for(let d = daISO(ordini[0].data), n = 0; (i < ordini.length || coda.length) && n < 800; d = sposta(d,1), n++){
        const iso = dataISO(d);
        if(lavorativo(d)){
            let cap = capacita(iso);
            const lavori = [];
            while(cap > 0 && coda.length){
                const voce = coda[0];
                const fatto = Math.min(cap, voce.resto);
                lavori.push({
                    ordine: voce.ordine,
                    minuti: fatto,
                    inizia: voce.resto === voce.totale,
                    finisce: voce.resto - fatto <= 0
                });
                voce.resto -= fatto;
                cap -= fatto;
                if(voce.resto <= 0) coda.shift();
            }
            if(lavori.length) programma[iso] = lavori;
        }
        while(i < ordini.length && ordini[i].data <= iso){
            const minuti = minutiCapi(ordini[i]);
            if(minuti > 0) coda.push({ ordine:ordini[i], resto:minuti, totale:minuti });
            i++;
        }
    }
    return programma;
}

