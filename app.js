/* Supabase restituisce al massimo 1000 righe per richiesta: si leggono a blocchi. */
async function tuttiGliOrdini(){
    const righe = [];
    for(let da = 0; ; da += 1000){
        const { data, error } = await sb.from("ordini").select("*").order("id").range(da, da + 999);
        if(error) throw error;
        righe.push(...data);
        if(data.length < 1000) return righe;
    }
}

/*
Legge tutto ciò che serve all'app. Gli ordini arrivano già filtrati dal
database (le sedi vedono solo i propri); il carico giornaliero invece
comprende tutte le sedi, senza nomi, per calcolare le date di ritiro.
*/
async function caricaDati(){
    const [config, turni, ordini, carico, prossimo] = await Promise.all([
        sb.from("config").select("chiave, valore"),
        sb.from("turni").select("data, turni"),
        tuttiGliOrdini(),
        sb.rpc("carico_giornaliero"),
        sb.rpc("prossimo_numero")
    ]);
    const fallita = [config, turni, carico, prossimo].find(r => r.error);
    if(fallita) throw fallita.error;

    db.config = { ...CONFIG_PREDEFINITA };
    config.data.forEach(r => db.config[r.chiave] = Number(r.valore));

    db.turni = {};
    turni.data.forEach(r => db.turni[r.data] = Number(r.turni));

    db.ordini = ordini.map(daRiga);

    /* arrivi: tutti i capi consegnati; carico: solo quelli ancora da stirare
       (gli ordini "pronto" e "ritirato" non pesano più sulle date di ritiro). */
    db.arrivi = {};
    db.carico = {};
    carico.data.forEach(r => {
        db.arrivi[r.data] = {};
        db.carico[r.data] = {};
        CAPI.forEach(c => {
            db.arrivi[r.data][c.k] = Number(r[c.k]) || 0;
            db.carico[r.data][c.k] = Number(r[c.k + "_aperte"]) || 0;
        });
    });

    db.prossimo = Number(prossimo.data) || null;
}

