/*
PDF vettoriale dell'etichetta: 100 × 62 mm orizzontale, solo nero,
testo nitido per la stampa termica Brother QL.
*/
function pdfEtichetta(o){
    const { jsPDF } = window.jspdf;
    const pdf = new jsPDF({ unit:"mm", format:[62,100], orientation:"landscape" });
    const sx = 4, dx = 96, larghezza = dx - sx;
    const creato = daISO(o.creato.slice(0,10));
    const taglia = (testo, max) => pdf.splitTextToSize(testo, max)[0];

    pdf.setTextColor(0);
    pdf.setDrawColor(0);

    /* Intestazione */
    pdf.addImage(LOGO, "PNG", sx, 3.2, 7.8, 9);
    pdf.setFont("helvetica","bold");
    pdf.setFontSize(7.5);
    pdf.text("ASSOCIAZIONE FREQUENZE", sx + 10, 6.8);
    pdf.setFont("helvetica","normal");
    pdf.setFontSize(6.5);
    pdf.text("Stireria · " + SEDI[o.sede], sx + 10, 10);

    pdf.setFontSize(5.5);
    pdf.text("ORDINE", dx, 5.8, { align:"right", charSpace:0.3 });
    pdf.setFont("courier","bold");
    pdf.setFontSize(14);
    pdf.text("N° " + numeroOrdine(o.id), dx, 11.2, { align:"right" });

    pdf.setLineWidth(0.35);
    pdf.line(sx, 13.6, dx, 13.6);

    /* Cliente */
    pdf.setFont("helvetica","bold");
    pdf.setFontSize(12);
    pdf.text(taglia(o.nome + " " + o.cognome, larghezza), sx, 19.6);
    pdf.setFont("helvetica","normal");
    pdf.setFontSize(7.5);
    pdf.text(taglia(telefonoLeggibile(o.telefono) + " · registrato il " +
        pad(creato.getDate()) + "." + pad(creato.getMonth()+1) + ". alle " + o.creato.slice(11), larghezza), sx, 23.8);

    /* Capi */
    pdf.setFont("helvetica","bold");
    pdf.setFontSize(9);
    pdf.splitTextToSize(testoCapiEtichetta(o), larghezza).slice(0,2)
        .forEach((riga, i) => pdf.text(riga, sx, 29.8 + i * 3.8));

    /* Ritiro */
    pdf.setLineWidth(0.45);
    pdf.roundedRect(sx, 38.5, larghezza, 19.5, 1.6, 1.6, "S");
    pdf.setFont("helvetica","normal");
    pdf.setFontSize(6);
    pdf.text("RITIRO", sx + 3, 43, { charSpace:0.3 });
    pdf.setFont("helvetica","bold");
    pdf.setFontSize(14);
    pdf.text(dataPunti(daISO(o.ritiro)), sx + 3, 49.6);
    pdf.setFont("helvetica","normal");
    pdf.setFontSize(7.5);
    pdf.text(ORA_RITIRO + " · presso " + SEDI[o.sede], sx + 3, 54.4);

    /* Solo se il cliente ha già pagato: riquadro nero "PAGATO" a destra. */
    if(o.pagato){
        pdf.setFillColor(0);
        pdf.roundedRect(dx - 26, 42, 23, 12.5, 1.2, 1.2, "F");
        pdf.setTextColor(255);
        pdf.setFont("helvetica","bold");
        pdf.setFontSize(11);
        pdf.text("PAGATO", dx - 14.5, 49.8, { align:"center" });
        pdf.setTextColor(0);
    }

    return pdf;
}

function righeCapi(lavori){
    return lavori.map((l,i) => {
        const o = l.ordine;
        const nota = [
            !l.inizia ? "continua dal giorno prima" : "",
            !l.finisce ? "prosegue il giorno dopo" : "",
            "ritiro " + dataBreve(daISO(o.ritiro))
        ].filter(Boolean).join(" · ");
        return `
            <tr>
                <td><span class="spunta"></span></td>
                <td class="n">${i+1}</td>
                <td><strong>${esc(o.nome)} ${esc(o.cognome)}</strong><span class="piccolo">#${numeroOrdine(o.id)} · ${SEDI[o.sede]}${o.lavare ? " · DA LAVARE" : ""} · ${nota}</span></td>
                ${CAPI.map(c => `<td class="n">${o[c.k] || "–"}</td>`).join("")}
                <td class="n">${durata(l.minuti)}</td>
            </tr>`;
    }).join("");
}

function apriPianoGiorno(iso){
    const d = daISO(iso);
    const lavori = programmaLavoro()[iso] || [];
    const totale = CAPI.reduce((t,c) => (t[c.k] = lavori.reduce((s,l) => s + l.ordine[c.k], 0), t), {});
    const minuti = lavori.reduce((s,l) => s + l.minuti, 0);

    const html = testaDocumento("Piano di lavoro", dataBreve(d), "Stireria · piano giornaliero") + `
        <h1>${dataLunga(d)}</h1>
        <p class="sottotitolo">${turniDi(iso)} turni da 4 ore · capacità ${durata(capacita(iso))} · lavoro previsto ${durata(minuti)} · ${lavori.length} ordini in ordine di arrivo</p>
        <h2>Ordini da stirare</h2>
        ${lavori.length ? `
        <table class="doc-tab">
            <thead><tr><th></th><th class="n">#</th><th>Cliente</th>${CAPI.map(c => `<th class="n">${c.breve}</th>`).join("")}<th class="n">Tempo</th></tr></thead>
            <tbody>${righeCapi(lavori)}</tbody>
            <tfoot><tr><td></td><td></td><td>Totale</td>${CAPI.map(c => `<td class="n">${totale[c.k]}</td>`).join("")}<td class="n">${durata(minuti)}</td></tr></tfoot>
        </table>` : '<p class="sottotitolo">Nessun ordine da stirare in questo giorno.</p>'}
        <p class="doc-nota">Le quantità sono quelle dell'intero ordine; il tempo è la parte prevista per questo giorno. Spuntare la casella a lavoro finito.</p>`;

    mostraDocumento("Piano di lavoro · " + dataLunga(d), html, "Piano-lavoro_" + iso + ".pdf");
}

function apriPianoSettimana(){
    const date = dateSettimana();
    const programma = programmaLavoro();
    const numero = numeroSettimana(lunediVisto);

    const righe = date.map(iso => {
        const lavori = programma[iso] || [];
        const somma = k => lavori.reduce((s,l) => s + l.ordine[k], 0);
        const minuti = lavori.reduce((s,l) => s + l.minuti, 0);
        const cap = capacita(iso);
        const riga = { iso, lavori, minuti, cap, ritiri: db.ordini.filter(o => o.ritiro === iso).length };
        CAPI.forEach(c => riga[c.k] = somma(c.k));
        return riga;
    });
    const tot = k => righe.reduce((s,r) => s + r[k], 0);

    const html = testaDocumento("Piano di lavoro", "Settimana " + numero, "Stireria · piano settimanale") + `
        <h1>Settimana ${numero}</h1>
        <p class="sottotitolo">${dataLunga(daISO(date[0]))} – ${dataLunga(daISO(date[4]))}</p>
        <h2>Riepilogo</h2>
        <table class="doc-tab">
            <thead><tr><th>Giorno</th><th class="n">Turni</th><th class="n">Capacità</th><th class="n">Lavoro previsto</th><th class="n">Ordini</th>${CAPI.map(c => `<th class="n">${c.breve}</th>`).join("")}<th class="n">Ritiri</th></tr></thead>
            <tbody>${righe.map(r => `
                <tr>
                    <td>${dataBreve(daISO(r.iso))}</td>
                    <td class="n">${turniDi(r.iso)}</td>
                    <td class="n">${durata(r.cap)}</td>
                    <td class="n">${durata(r.minuti)}</td>
                    <td class="n">${r.lavori.length}</td>
                    ${CAPI.map(c => `<td class="n">${r[c.k]}</td>`).join("")}
                    <td class="n">${r.ritiri}</td>
                </tr>`).join("")}</tbody>
            <tfoot><tr><td>Totale</td><td class="n">${date.reduce((s,d) => s + turniDi(d), 0)}</td><td class="n">${durata(tot("cap"))}</td><td class="n">${durata(tot("minuti"))}</td><td></td>${CAPI.map(c => `<td class="n">${tot(c.k)}</td>`).join("")}<td class="n">${tot("ritiri")}</td></tr></tfoot>
        </table>
        <p class="doc-nota">Capi: quelli degli ordini lavorati in quel giorno (un ordine diviso su due giorni compare in entrambi). Ritiri: ordini che i clienti ritirano quel giorno ${ORA_RITIRO}.</p>`;

    mostraDocumento("Piano di lavoro · settimana " + numero, html, "Piano-lavoro_settimana-" + numero + ".pdf");
}

