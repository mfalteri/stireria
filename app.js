$("#formOrdine").addEventListener("submit", async e => {
    e.preventDefault();
    if(ordineRegistrato) return;

    const nome = $("#nome").value.trim();
    const cognome = $("#cognome").value.trim();
    const telefono = normalizzaTelefono($("#telefono").value);
    const capi = capiInseriti();

    if(!nome) return mostraErroreOrdine("Inserisci il nome del cliente.","nome");
    if(!cognome) return mostraErroreOrdine("Inserisci il cognome del cliente.","cognome");
    const erroreTelefono = controllaTelefono(telefono);
    if(erroreTelefono) return mostraErroreOrdine(erroreTelefono,"telefono");
    if(minutiCapi(capi) <= 0) return mostraErroreOrdine("Aggiungi almeno un capo da stirare.");
    if(!ritiroScelto) return mostraErroreOrdine("Scegli il giorno di ritiro.");

    mostraErroreOrdine("");

    const pulsante = $("#registra");
    pulsante.disabled = true;
    pulsante.querySelector("strong").textContent = "Registrazione…";

    const { data:riga, error } = await sb.from("ordini").insert({
        data: dataISO(giornoDeposito(oggi())),
        sede: utente.sede || sedeOrdine,
        nome, cognome, telefono, ...capi,
        ritiro: ritiroScelto,
        lavare: $("#lavare").checked,
        pagato: $("#pagato").checked
    }).select().single();

    if(error){
        pulsante.disabled = false;
        pulsante.querySelector("strong").textContent = "Conferma ordine";
        return erroreDatabase(error, "Registrazione dell'ordine");
    }

    const ordine = daRiga(riga);
    db.ordini.push(ordine);
    ricarica();

    ordineRegistrato = ordine;
    etichettaAperta = false;
    ricevutaAperta = false;
    bloccaModulo(true);
    aggiornaTicket();
    aggiornaBadge();
    $("#stampaEtichetta").focus();
});

