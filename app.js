$("#scaricaPdf").addEventListener("click", async () => {
    const b = $("#scaricaPdf");
    if(!window.html2canvas || !window.jspdf) return;

    if(documentoCorrente.tipo === "etichetta"){
        pdfEtichetta(documentoCorrente.ordine).save(nomeFilePdf);
        return;
    }

    b.disabled = true;
    b.textContent = "Creazione PDF…";
    try{
        const canvas = await html2canvas($("#foglio"), {
            scale:2,
            backgroundColor:"#ffffff",
            windowWidth:1000,
            onclone: copia => {
                const f = copia.getElementById("foglio");
                f.style.width = "794px";
                f.style.maxWidth = "none";
                f.style.padding = "0";
                f.style.boxShadow = "none";
            }
        });
        const { jsPDF } = window.jspdf;
        const pdf = new jsPDF({ unit:"mm", format:"a4" });
        const margine = 14, larghezza = 210 - margine * 2;
        const pxPerMm = canvas.width / larghezza;
        const altezzaPagina = Math.floor((297 - margine * 2) * pxPerMm);

        for(let y = 0, pagina = 0; y < canvas.height; y += altezzaPagina, pagina++){
            const h = Math.min(altezzaPagina, canvas.height - y);
            const parte = document.createElement("canvas");
            parte.width = canvas.width;
            parte.height = h;
            const ctx = parte.getContext("2d");
            ctx.fillStyle = "#fff";
            ctx.fillRect(0,0,parte.width,h);
            ctx.drawImage(canvas, 0, y, canvas.width, h, 0, 0, canvas.width, h);
            if(pagina > 0) pdf.addPage();
            pdf.addImage(parte.toDataURL("image/jpeg",0.92), "JPEG", margine, margine, larghezza, h / pxPerMm);
        }
        pdf.save(nomeFilePdf);
    }finally{
        b.disabled = false;
        b.textContent = "Scarica PDF";
    }
});

