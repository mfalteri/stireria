/* 41791234567 → +41 79 123 45 67 (gli altri numeri restano con il solo "+") */
function telefonoLeggibile(n){
    n = normalizzaTelefono(n);
    return /^41\d{9}$/.test(n)
        ? "+41 " + n.slice(2,4) + " " + n.slice(4,7) + " " + n.slice(7,9) + " " + n.slice(9)
        : "+" + n;
}

