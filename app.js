/* ---------- Domanda sì / no (i dialoghi del browser non sono disponibili ovunque) ---------- */

function chiedi(titolo, testo, opzioni){
    return new Promise(risolvi => {
        const velo = $("#dialogo");
        $("#dialogoTitolo").textContent = titolo;
        $("#dialogoTesto").textContent = testo || "";
        $("#dialogoTesto").hidden = !testo;
        const azioni = $("#dialogoAzioni");
        azioni.innerHTML = "";

        const chiudi = valore => {
            velo.hidden = true;
            document.removeEventListener("keydown", tasto);
            risolvi(valore);
        };
        const tasto = e => { if(e.key === "Escape") chiudi(null); };

        opzioni.forEach(o => {
            const b = document.createElement("button");
            b.type = "button";
            b.className = "btn" + (o.primario ? " btn-primario" : "");
            b.textContent = o.testo;
            b.addEventListener("click", () => chiudi(o.valore));
            azioni.appendChild(b);
        });

        velo.onclick = e => { if(e.target === velo) chiudi(null); };
        document.addEventListener("keydown", tasto);
        velo.hidden = false;
        azioni.lastChild.focus();
    });
}

