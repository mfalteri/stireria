/* Turni: si salvano solo i giorni diversi dal numero predefinito. */
$("#righeGiorni").addEventListener("change", async e => {
    const input = e.target.closest(".turni-input");
    if(!input) return;
    const data = input.dataset.data;
    const v = Math.max(0, parseInt(input.value) || 0);
    const precedente = db.turni[data];

    if(v === db.config.turniDefault) delete db.turni[data];
    else db.turni[data] = v;
    disegnaCarico();

    const { error } = v === db.config.turniDefault
        ? await sb.from("turni").delete().eq("data", data)
        : await sb.from("turni").upsert({ data, turni:v });

    if(error){
        if(precedente === undefined) delete db.turni[data];
        else db.turni[data] = precedente;
        disegnaCarico();
        return erroreDatabase(error, "Salvataggio dei turni");
    }
    avvisa("Turni di " + dataBreve(daISO(data)) + " salvati");
});

